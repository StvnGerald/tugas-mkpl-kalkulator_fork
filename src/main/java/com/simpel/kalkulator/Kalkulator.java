package com.simpel.kalkulator;

public class Kalkulator {
    public int tambah(int a, int b) {
        return a + b;
    }

    public int kurang(int a, int b) {
        return a - b;
    }
    public int kali(int a, int b){
        return a * b;
    }
    
    public double bagi(double a, double b){
        return a / b;
    }
}
